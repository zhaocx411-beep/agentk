"""模型通道对音频素材的处理方式。

单独成文件是因为判定链路和 `/api/health` 都要读它，表散在两处必然漂移，表现是
一处说能判、另一处其实跳过。

两档的区别是"能判到什么程度"，不是"能不能提交"：

* `full`（agentk）——音频原生送进模型，音色、语调、配乐风格都能判。**有前提**：只在
  音频阶段成立，且模型得挑对，见下；
* `ignored`——直接跳过音频，声音相关结论全是未核实。未登记通道的默认值，
  见 ``audio_support``。

曾经还有 `transcribe` 一档（独立音频先经 transcribe_audio 转成文字再送）。那条通路
2026-09-03 下线——它在 prod 挂着不返回，把主流程拖死，见 agentk_audio 的模块说明。
现在非音频阶段的独立音频是**彻底送不进去**，不是降级成文字。

**这张表说的是「独立音频文件」怎么处理，不等于"模型听不到声音"**——视频自带的音轨
其实进得去，见下方。这个区分很要紧，原先混为一谈过一次。

## 视频音轨进得去，独立音频文件进不去（2026-09-01 实测）

先说被推翻的旧结论。这里此前断言这三条子准则「永久无法核实」：

    audio_signal_quality        有无爆音、底噪、削波
    audio_av_sync               口型与声音是否对齐
    audio_temporal_consistency  音量/音色跨镜头是否连贯

推理是"schema 不收音频 → 音频进不了模型"。**前提错了**：mp4 本身带音轨，而平台是把
视频 URL 透传给 Gemini（原生支持带声音的视频），音轨因此一路进到了模型里。

`scripts/probe_audio_passthrough.py` 用视听解耦的方式验过：画面是测试图案（无口型、
无字幕），音轨换成自己合成的胡话，提示词不注入任何转写文本。模型三轮都把那句胡话逐字
复述了出来，其中一个字 transcribe_audio 反而听错——只能是模型自己听到的。

但**精度有限**：同三轮里纯音调的数量答 2/3/4（真值 3），时间偏差约 1 秒。所以
"人声内容可判"确凿，"逐帧口型对齐、爆音计数可判"没验证过，别顺着推。要改判定口径请
先重跑那个探针，平台行为会变。

## 独立音频文件：2026-09-01 起进得去，但要挑模型

平台当天 16:05 放开 mediaUrls 收音频。能不能用**取决于用哪个模型**，这是整件事里最容易
踩错的一处：

* 主模型（pro）——约一半的调用会在服务端把音频转成文字再交给模型。接口通、台词对、
  还带时间戳，只有音色/语调/音质/配乐拿不到，报告里看不出任何异常（实测 28 次里 13 次）；
* audio_model（flash-lite）——实测 8/8 真拿到音频。

所以 agentk 记 `full`，但**只在音频阶段成立**：判定链按阶段分派模型，音频阶段走
audio_model，其余阶段的独立音频送不进去、只在提示词里标明"这次听不到"（见
config.AgentKConfig.audio_model 与 providers/agentk_audio 的模块说明）。这张表描述的是
"这个通道最好能判到什么程度"，不是"每次调用都这么判"。

**flash-lite 的短板**：对非语音声音事件不敏感——三声与人声同响度的 1000Hz 纯音 8 次全漏。
所以整体音质、音色、语调、配乐风格可以真判，**瞬态缺陷（单次爆音、削波、一闪而过的杂音）
不能顺着推**。这条写进了注入措辞，让模型没听出来时记 not_observable 而不是"无此问题"。

套一层黑底视频送（``--wrap-audio``）也验证可行，但既然有了原生入口就不用它了：那种绕法
绕的正是 schema 校验，平台收紧时不会报错，只会让音频判据悄悄退化。探针脚本留着作复核。
此前还留过一条能内联音频的 Gemini 直连作退路，但它零流量、与判定链路早已脱节，已删除
——**不要**为这个缺口重建它。
"""

from __future__ import annotations

AUDIO_SUPPORT: dict[str, str] = {
    "agentk": "full",
}


def audio_support(provider: str) -> str:
    """未登记的通道按 ignored 处理：宁可说"判不了"，也不要许诺一个没实现的能力。"""
    return AUDIO_SUPPORT.get((provider or "").strip().lower(), "ignored")
