"""agentk 通道的音频注入措辞：告诉模型这次它到底能不能听见。

音频只剩两条路，取决于这次调用派到哪个模型：

1. **视频自带音轨** —— 随 mp4 一路进到模型里，模型听得到。这条一直成立，与平台
   放开音频入口无关（2026-09-01 实测，见 scripts/probe_audio_passthrough.py）。
2. **独立音频文件** —— 只在走 audio_model（flash-lite）的阶段送进 mediaUrls，
   实测 8/8 真拿到音频。其他模型上不送：pro 有约一半的调用会在服务端把音频转成
   文字再注入（见 config.AgentKConfig.audio_model），接口通、台词还对，只有音色、
   语调、音质、配乐拿不到，报告里看不出任何异常。与其许诺一个一半概率不成立的
   能力，不如明说"这次听不到"，让判据老实记 not_observable。

## 为什么没有转写了

曾经还有第三条：用 `agentk.transcribe_audio`（azure-whisper）把音频转成带时间轴的
文字随提示词送。它提供两样多余的东西——精确到句的时间轴，以及一份可对照的文字。
2026-09-03 下线，两个理由：

* **它在生产环境不可用。** prod 上这个能力挂着不返回也不报错，120 秒等待上限耗尽
  才拿到超时。而失败结果没法缓存，worker 路径上每一遍重放都要重付一次，四次叠加
  直接顶穿 observe 阶段 420 秒的 activity 预算，整条质检失败。一个旁路证据把主流程
  拖死，这个代价比它提供的时间轴贵得多。
* **它的价值已经被 flash-lite 吃掉大半。** 音频判据现在集中在 4a（参考音频对照）与
  4c（音频独立复听）两个阶段，它们都跑在真听得见的模型上。

代价要说清楚：**没有精确时间轴了**。模型自报的时间点偏差约 1 秒，所以"第 3.2 秒那声
爆音"这种精度的结论不再可靠，音画同步只能给到"大致对齐/明显不同步"这一档。
"""

from __future__ import annotations

# 两段注入措辞，对应两种**处境完全相反**的情形。绝不能共用一段：说错方向的后果是
# 静默的——要么让模型凭空回避一个它真有的能力（音频维度长期停在未核实），要么让它
# 凭想象给一个没有听觉依据的结论（报告看起来完整，实则编的）。

# 这次调用听得见（视频音轨，或走 audio_model 的独立音频）。
#
# 末尾那句边界是实测出来的，不是客套：flash-lite 对**非语音声音事件**不敏感
# （2026-09-01 同批实测里，与人声同响度的三声纯音 0/8 被提到）。所以不能顺着让它去
# 数爆音、削波这类瞬态缺陷——那会把"没注意到"变成"没有问题"。
AUDIBLE_AUDIO_NOTE = (
    "说明：你可以**直接听到**这段音频。"
    "音质、音色、语调、语速、配乐风格请依据你实际听到的内容判断，"
    "不要因为「只有文字」而回避——那是过时的限制。"
    "两点边界：没有逐句时间轴可参照，所以时间点只能给大致范围，不要谎报精确到秒；"
    "短促的瞬态声音（单次爆音、削波、一闪而过的杂音）你未必能注意到，"
    "没听出来时请记 not_observable，不要写成「无此问题」。"
)

# 这次调用听不见（独立音频文件 + 非 audio_model）。
#
# 仍然要把"有这么一段音频"说出来，不能干脆不提：不提的话模型会把音频要求当成
# 没有要求，声音相关的子判据会被判成 pass 而不是 not_observable——一个不报错、
# 看不出来的错误结论。
INAUDIBLE_AUDIO_NOTE = (
    "说明：本次调用**拿不到这段音频的任何内容**——听不到声音，也没有转写文字。"
    "凡是依赖这段音频的要求一律记 not_observable，不得凭文件名或上下文推断。"
    "音频要求由专门的音频阶段（跑在听得见的模型上）另行核实，不必在这里勉强下结论。"
)
